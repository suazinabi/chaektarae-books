import { initializeTestEnvironment, assertFails, assertSucceeds } from '@firebase/rules-unit-testing';
import { doc, setDoc, updateDoc, getDoc, deleteDoc, serverTimestamp, deleteField, Timestamp } from 'firebase/firestore';
import fs from 'fs';
const env = await initializeTestEnvironment({ projectId: 'demo-rules', firestore: { rules: fs.readFileSync('firestore.rules', 'utf8'), host: '127.0.0.1', port: 8080 } });
const A = env.authenticatedContext('A').firestore(), B = env.authenticatedContext('B').firestore(), N = env.unauthenticatedContext().firestore();
const ok = [], bad = [];
const t = async (name, p, should) => { try { await (should ? assertSucceeds(p) : assertFails(p)); ok.push(name) } catch (e) { bad.push(name + ' :: ' + e.message.slice(0, 120)) } };
const post = { uid: 'A', x: '안녕', ts: serverTimestamp(), r: '', pu: '', lk: {}, rp: {} };
await t('A creates post', setDoc(doc(A, 'posts/p1'), post), 1);
await t('anon cannot read', getDoc(doc(N, 'posts/p1')), 0);
await t('B reads', getDoc(doc(B, 'posts/p1')), 1);
await t('B cannot post as A', setDoc(doc(B, 'posts/p2'), post), 0);
await t('fake ts rejected', setDoc(doc(A, 'posts/p3'), { ...post, ts: Timestamp.fromMillis(1) }), 0);
await t('extra field rejected', setDoc(doc(A, 'posts/p4'), { ...post, img: 'x' }), 0);
await t('too long rejected', setDoc(doc(A, 'posts/p5'), { ...post, x: 'a'.repeat(501) }), 0);
await t('prefilled likes rejected', setDoc(doc(A, 'posts/p6'), { ...post, lk: { B: true } }), 0);
await t('B edits text', updateDoc(doc(B, 'posts/p1'), { x: 'hacked' }), 0);
await t('B likes', updateDoc(doc(B, 'posts/p1'), { 'lk.B': true }), 1);
await t('B likes as A', updateDoc(doc(B, 'posts/p1'), { 'lk.A': true }), 0);
await t('B unlikes', updateDoc(doc(B, 'posts/p1'), { 'lk.B': deleteField() }), 1);
await t('B reports', updateDoc(doc(B, 'posts/p1'), { 'rp.B': '욕설' }), 1);
await t('B deletes A post', deleteDoc(doc(B, 'posts/p1')), 0);
await t('user profile ok', setDoc(doc(A, 'users/A'), { name: '에이', handle: 'aaa', bio: '', color: '#a89a88', ts: serverTimestamp(), age14: true }), 1);
await t('profile without age14', setDoc(doc(B, 'users/B'), { name: '비', handle: 'bbb', bio: '', color: '#a89a88', ts: serverTimestamp(), age14: false }), 0);
await t('B writes A profile', setDoc(doc(B, 'users/A'), { name: 'x', handle: 'xxx', bio: '', color: '#a89a88', ts: serverTimestamp(), age14: true }), 0);
await t('handle claim for other', setDoc(doc(B, 'handles/zzz'), { uid: 'A' }), 0);
await env.withSecurityRulesDisabled(async c => { await setDoc(doc(c.firestore(), 'bans/B'), { why: 'spam' }) });
await t('banned cannot post', setDoc(doc(B, 'posts/p9'), { ...post, uid: 'B' }), 0);
await t('A deletes own', deleteDoc(doc(A, 'posts/p1')), 1);
console.log('PASS', ok.length, '\nFAIL', bad.length, bad.join('\n'));
await env.cleanup();
